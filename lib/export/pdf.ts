// Client-side PDF export for work reports, work logs, and plans.
// Generated in the browser from data already on screen — no server runtime, works on a bad connection.
// Uses jspdf + jspdf-autotable. Three layouts: report, log, plan.

import { jsPDF } from "jspdf"
import autoTable from "jspdf-autotable"
import type { ReportDto } from "@/lib/reports/report-fields"
import type { ReportAggregate } from "@/lib/reports/aggregate"
import type { EntryDto, DeliverableDto } from "@/lib/worklog/entries"

export type ReportExportData = {
  report: ReportDto
  metrics: ReportAggregate
  authorName: string
  recipientNames: string[]
}

export type LogExportData = {
  entries: EntryDto[]
  deliverables: DeliverableDto[]
  from: string
  to: string
  authorName: string
}

export type PlanExportData = {
  title: string
  horizon: string
  lanes: { name: string; items: { title: string; start: string; end: string; status: string }[] }[]
}

function filename(scope: string, stamp: string): string {
  return `jiravision-${scope}-${stamp}.pdf`
}

function addFooter(doc: jsPDF) {
  const pageCount = doc.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setFontSize(9)
    doc.setTextColor(128)
    doc.text(`Page ${i} of ${pageCount}`, doc.internal.pageSize.getWidth() / 2, 10, { align: "center" })
    doc.text(`Generated by JiraVision · ${new Date().toISOString().slice(0, 10)}`, 14, doc.internal.pageSize.getHeight() - 10)
  }
}

export function exportReportPdf(data: ReportExportData): void {
  const { report, metrics, authorName, recipientNames } = data
  const doc = new jsPDF()
  const stamp = report.submittedAt?.slice(0, 10) ?? report.createdAt.slice(0, 10)

  // Cover block
  doc.setFontSize(20)
  doc.setFont("helvetica", "bold")
  doc.text(report.title || "Work Report", 14, 25)

  doc.setFontSize(11)
  doc.setFont("helvetica", "normal")
  doc.text(`Author: ${authorName}`, 14, 35)
  doc.text(`Period: ${metrics.period.label}`, 14, 42)
  doc.text(`Template: ${report.template}`, 14, 49)
  doc.text(`Status: ${report.status}`, 14, 56)
  if (report.revisionOf) {
    doc.text(`Revision of: #${report.revisionOf}`, 14, 63)
  }
  doc.text(`Recipients: ${recipientNames.join(", ") || "None"}`, 14, 70)

  // KPI strip
  const kpiY = 85
  doc.setFontSize(10)
  doc.setFont("helvetica", "bold")
  const kpis = [
    { label: "Entries", value: metrics.metrics.taskEvents.value },
    { label: "Hours", value: Math.round(metrics.metrics.minutes.value / 60) },
    { label: "Tasks done", value: metrics.metrics.completedTasks.value },
    { label: "Deliverables", value: metrics.metrics.deliverablesProduced.value },
    { label: "Blockers", value: metrics.metrics.blockedTasks.value },
  ]
  const kpiWidth = 35
  kpis.forEach((kpi, i) => {
    const x = 14 + i * kpiWidth
    doc.text(kpi.label, x, kpiY)
    doc.setFont("helvetica", "normal")
    doc.text(String(kpi.value), x, kpiY + 7)
    doc.setFont("helvetica", "bold")
  })

  // Sections as tables
  let currentY = 110

  if (metrics.deliverableRows.length > 0 && currentY < 250) {
    doc.setFontSize(14)
    doc.text("Deliverables", 14, currentY)
    currentY += 5
    autoTable(doc, {
      startY: currentY,
      head: [["Title", "Detail", "Date"]],
      body: metrics.deliverableRows.slice(0, 30).map((r) => [r.title, r.detail, r.date ?? ""]),
      theme: "striped",
      headStyles: { fillColor: [41, 128, 185] },
    })
    currentY = (doc as any).lastAutoTable.finalY + 10
  }

  if (metrics.completed.length > 0 && currentY < 250) {
    doc.setFontSize(14)
    doc.text("Completed Tasks", 14, currentY)
    currentY += 5
    autoTable(doc, {
      startY: currentY,
      head: [["Title", "Detail", "Date"]],
      body: metrics.completed.slice(0, 30).map((r) => [r.title, r.detail, r.date ?? ""]),
      theme: "striped",
      headStyles: { fillColor: [41, 128, 185] },
    })
  }

  addFooter(doc)
  doc.save(filename("report", stamp))
}

export function exportLogPdf(data: LogExportData): void {
  const { entries, deliverables, from, to, authorName } = data
  const doc = new jsPDF()
  const stamp = from

  // Header
  doc.setFontSize(18)
  doc.setFont("helvetica", "bold")
  doc.text("Work Log", 14, 25)

  doc.setFontSize(11)
  doc.setFont("helvetica", "normal")
  doc.text(`Author: ${authorName}`, 14, 35)
  doc.text(`Period: ${from} to ${to}`, 14, 42)

  // Entries table
  let currentY = 55
  if (entries.length > 0) {
    doc.setFontSize(14)
    doc.setFont("helvetica", "bold")
    doc.text("Entries", 14, currentY)
    currentY += 5
    autoTable(doc, {
      startY: currentY,
      head: [["Date", "Title", "Kind", "Minutes", "Task"]],
      body: entries.map((e) => [e.workedOn, e.title, e.kind, e.minutes ?? "", e.taskId ?? ""]),
      theme: "striped",
      headStyles: { fillColor: [41, 128, 185] },
    })
    currentY = (doc as any).lastAutoTable.finalY + 10
  }

  // Deliverables table
  if (deliverables.length > 0 && currentY < 250) {
    doc.setFontSize(14)
    doc.setFont("helvetica", "bold")
    doc.text("Deliverables", 14, currentY)
    currentY += 5
    autoTable(doc, {
      startY: currentY,
      head: [["Title", "Status", "Delivered On"]],
      body: deliverables.map((d) => [d.name, d.status, d.producedOn ?? ""]),
      theme: "striped",
      headStyles: { fillColor: [41, 128, 185] },
    })
  }

  addFooter(doc)
  doc.save(filename("log", stamp))
}

export function exportPlanPdf(data: PlanExportData): void {
  const { title, horizon, lanes } = data
  const doc = new jsPDF()
  const stamp = new Date().toISOString().slice(0, 10)

  // Header
  doc.setFontSize(18)
  doc.setFont("helvetica", "bold")
  doc.text(title || "Forward Plan", 14, 25)

  doc.setFontSize(11)
  doc.setFont("helvetica", "normal")
  doc.text(`Horizon: ${horizon}`, 14, 35)

  // Lane-grouped table
  let currentY = 50
  for (const lane of lanes) {
    if (currentY > 260) {
      doc.addPage()
      currentY = 20
    }
    doc.setFontSize(13)
    doc.setFont("helvetica", "bold")
    doc.text(lane.name, 14, currentY)
    currentY += 5

    if (lane.items.length > 0) {
      autoTable(doc, {
        startY: currentY,
        head: [["Title", "Start", "End", "Status"]],
        body: lane.items.map((item) => [item.title, item.start, item.end, item.status]),
        theme: "striped",
        headStyles: { fillColor: [41, 128, 185] },
      })
      currentY = (doc as any).lastAutoTable.finalY + 8
    } else {
      currentY += 5
    }
  }

  addFooter(doc)
  doc.save(filename("plan", stamp))
}
