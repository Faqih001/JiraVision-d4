// Client-side PDF export for work reports, work logs, plans, and playbooks.
// Generated in the browser from data already on screen — no server runtime, works on a bad connection.
// Uses jspdf + jspdf-autotable. Four layouts: report, log, plan, playbook.

import { jsPDF } from "jspdf"
import autoTable from "jspdf-autotable"
import type { ReportDto } from "@/lib/reports/report-fields"
import type { ReportAggregate } from "@/lib/reports/aggregate"
import type { EntryDto, DeliverableDto } from "@/lib/worklog/entries"
import type { PlaybookStep } from "@/lib/playbooks/method"

export type ReportExportData = {
  report: ReportDto
  metrics: ReportAggregate
  authorName: string
  recipientNames: string[]
}

export type LogExportData = {
  entries: EntryDto[]
  deliverables: DeliverableDto[]
  from: string
  to: string
  authorName: string
}

export type PlanExportData = {
  title: string
  horizon: string
  lanes: { name: string; items: { title: string; start: string; end: string; status: string }[] }[]
}

export type PlaybookExportData = {
  title: string
  summary: string | null
  packKey: string
  discipline: string | null
  version: number
  status: string
  /** True while the prose is model-authored and no person has reviewed it yet. */
  aiMarked: boolean
  authorName: string | null
  method: string[]
  steps: PlaybookStep[]
  precautions: string[]
  recommendations: string[]
  lastVerifiedAt: string | null
  verifyIntervalDays: number | null
}

function filename(scope: string, stamp: string): string {
  return `jiravision-${scope}-${stamp}.pdf`
}

function addFooter(doc: jsPDF) {
  const pageCount = doc.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setFontSize(9)
    doc.setTextColor(128)
    doc.text(`Page ${i} of ${pageCount}`, doc.internal.pageSize.getWidth() / 2, 10, { align: "center" })
    doc.text(`Generated by JiraVision · ${new Date().toISOString().slice(0, 10)}`, 14, doc.internal.pageSize.getHeight() - 10)
  }
}

export function exportReportPdf(data: ReportExportData): void {
  const { report, metrics, authorName, recipientNames } = data
  const doc = new jsPDF()
  const stamp = report.submittedAt?.slice(0, 10) ?? report.createdAt.slice(0, 10)

  // Cover block
  doc.setFontSize(20)
  doc.setFont("helvetica", "bold")
  doc.text(report.title || "Work Report", 14, 25)

  doc.setFontSize(11)
  doc.setFont("helvetica", "normal")
  doc.text(`Author: ${authorName}`, 14, 35)
  doc.text(`Period: ${metrics.period.label}`, 14, 42)
  doc.text(`Template: ${report.template}`, 14, 49)
  doc.text(`Status: ${report.status}`, 14, 56)
  if (report.revisionOf) {
    doc.text(`Revision of: #${report.revisionOf}`, 14, 63)
  }
  doc.text(`Recipients: ${recipientNames.join(", ") || "None"}`, 14, 70)

  // KPI strip
  const kpiY = 85
  doc.setFontSize(10)
  doc.setFont("helvetica", "bold")
  const kpis = [
    { label: "Entries", value: metrics.metrics.taskEvents.value },
    { label: "Hours", value: Math.round(metrics.metrics.minutes.value / 60) },
    { label: "Tasks done", value: metrics.metrics.completedTasks.value },
    { label: "Deliverables", value: metrics.metrics.deliverablesProduced.value },
    { label: "Blockers", value: metrics.metrics.blockedTasks.value },
  ]
  const kpiWidth = 35
  kpis.forEach((kpi, i) => {
    const x = 14 + i * kpiWidth
    doc.text(kpi.label, x, kpiY)
    doc.setFont("helvetica", "normal")
    doc.text(String(kpi.value), x, kpiY + 7)
    doc.setFont("helvetica", "bold")
  })

  // Sections as tables
  let currentY = 110

  if (metrics.deliverableRows.length > 0 && currentY < 250) {
    doc.setFontSize(14)
    doc.text("Deliverables", 14, currentY)
    currentY += 5
    autoTable(doc, {
      startY: currentY,
      head: [["Title", "Detail", "Date"]],
      body: metrics.deliverableRows.slice(0, 30).map((r) => [r.title, r.detail, r.date ?? ""]),
      theme: "striped",
      headStyles: { fillColor: [41, 128, 185] },
    })
    currentY = (doc as any).lastAutoTable.finalY + 10
  }

  if (metrics.completed.length > 0 && currentY < 250) {
    doc.setFontSize(14)
    doc.text("Completed Tasks", 14, currentY)
    currentY += 5
    autoTable(doc, {
      startY: currentY,
      head: [["Title", "Detail", "Date"]],
      body: metrics.completed.slice(0, 30).map((r) => [r.title, r.detail, r.date ?? ""]),
      theme: "striped",
      headStyles: { fillColor: [41, 128, 185] },
    })
  }

  addFooter(doc)
  doc.save(filename("report", stamp))
}

export function exportLogPdf(data: LogExportData): void {
  const { entries, deliverables, from, to, authorName } = data
  const doc = new jsPDF()
  const stamp = from

  // Header
  doc.setFontSize(18)
  doc.setFont("helvetica", "bold")
  doc.text("Work Log", 14, 25)

  doc.setFontSize(11)
  doc.setFont("helvetica", "normal")
  doc.text(`Author: ${authorName}`, 14, 35)
  doc.text(`Period: ${from} to ${to}`, 14, 42)

  // Entries table
  let currentY = 55
  if (entries.length > 0) {
    doc.setFontSize(14)
    doc.setFont("helvetica", "bold")
    doc.text("Entries", 14, currentY)
    currentY += 5
    autoTable(doc, {
      startY: currentY,
      head: [["Date", "Title", "Kind", "Minutes", "Task"]],
      body: entries.map((e) => [e.workedOn, e.title, e.kind, e.minutes ?? "", e.taskId ?? ""]),
      theme: "striped",
      headStyles: { fillColor: [41, 128, 185] },
    })
    currentY = (doc as any).lastAutoTable.finalY + 10
  }

  // Deliverables table
  if (deliverables.length > 0 && currentY < 250) {
    doc.setFontSize(14)
    doc.setFont("helvetica", "bold")
    doc.text("Deliverables", 14, currentY)
    currentY += 5
    autoTable(doc, {
      startY: currentY,
      head: [["Title", "Status", "Delivered On"]],
      body: deliverables.map((d) => [d.name, d.status, d.producedOn ?? ""]),
      theme: "striped",
      headStyles: { fillColor: [41, 128, 185] },
    })
  }

  addFooter(doc)
  doc.save(filename("log", stamp))
}

export function exportPlanPdf(data: PlanExportData): void {
  const { title, horizon, lanes } = data
  const doc = new jsPDF()
  const stamp = new Date().toISOString().slice(0, 10)

  // Header
  doc.setFontSize(18)
  doc.setFont("helvetica", "bold")
  doc.text(title || "Forward Plan", 14, 25)

  doc.setFontSize(11)
  doc.setFont("helvetica", "normal")
  doc.text(`Horizon: ${horizon}`, 14, 35)

  // Lane-grouped table
  let currentY = 50
  for (const lane of lanes) {
    if (currentY > 260) {
      doc.addPage()
      currentY = 20
    }
    doc.setFontSize(13)
    doc.setFont("helvetica", "bold")
    doc.text(lane.name, 14, currentY)
    currentY += 5

    if (lane.items.length > 0) {
      autoTable(doc, {
        startY: currentY,
        head: [["Title", "Start", "End", "Status"]],
        body: lane.items.map((item) => [item.title, item.start, item.end, item.status]),
        theme: "striped",
        headStyles: { fillColor: [41, 128, 185] },
      })
      currentY = (doc as any).lastAutoTable.finalY + 8
    } else {
      currentY += 5
    }
  }

  addFooter(doc)
  doc.save(filename("plan", stamp))
}

// The shop-floor sheet. One page per phase, each step laid out as field/detail rows so a
// technician can read it at arm's length, and a signature block at the foot of every phase
// — the printed record of who followed this version and when.
export function exportPlaybookPdf(data: PlaybookExportData): void {
  const doc = new jsPDF()
  const stamp = new Date().toISOString().slice(0, 10)

  doc.setFontSize(20)
  doc.setFont("helvetica", "bold")
  doc.text(data.title || "Playbook", 14, 25)

  doc.setFontSize(11)
  doc.setFont("helvetica", "normal")
  doc.text(`Version: v${data.version} (${data.status})`, 14, 35)
  doc.text(`Role pack: ${data.packKey}`, 14, 42)
  if (data.discipline) doc.text(`Discipline: ${data.discipline}`, 14, 49)
  doc.text(`Author: ${data.authorName ?? "Unknown"}`, 14, 56)
  doc.text(
    `Last verified: ${data.lastVerifiedAt ?? "Never"}${
      data.verifyIntervalDays === null ? "" : ` · re-verify every ${data.verifyIntervalDays} days`
    }`,
    14,
    63,
  )

  let currentY = 74
  if (data.summary) {
    const lines = doc.splitTextToSize(data.summary, 180) as string[]
    doc.text(lines, 14, currentY)
    currentY += lines.length * 5 + 6
  }

  if (data.aiMarked) {
    doc.setTextColor(180, 83, 9)
    const lines = doc.splitTextToSize(
      "Model draft — this sheet has not been reviewed by a person. Treat every precaution as a suggestion until it is.",
      180,
    ) as string[]
    doc.text(lines, 14, currentY)
    doc.setTextColor(0)
    currentY += lines.length * 5 + 6
  }

  doc.setFontSize(13)
  doc.setFont("helvetica", "bold")
  doc.text("Method", 14, currentY)
  currentY += 6
  doc.setFontSize(10)
  doc.setFont("helvetica", "normal")
  const methodLines = doc.splitTextToSize(
    data.method.map((phase, index) => `${index + 1}. ${phase}`).join("   "),
    180,
  ) as string[]
  doc.text(methodLines, 14, currentY)
  currentY += methodLines.length * 5 + 8

  if (data.precautions.length > 0) {
    doc.setFontSize(13)
    doc.setFont("helvetica", "bold")
    doc.text(data.aiMarked ? "Precautions (model-drafted)" : "Precautions", 14, currentY)
    currentY += 4
    autoTable(doc, {
      startY: currentY,
      head: [["#", "Precaution"]],
      body: data.precautions.map((entry, index) => [String(index + 1), entry]),
      theme: "grid",
      headStyles: { fillColor: [41, 128, 185] },
      columnStyles: { 0: { cellWidth: 10 } },
    })
    currentY = (doc as any).lastAutoTable.finalY + 10
  }

  if (data.recommendations.length > 0) {
    doc.setFontSize(13)
    doc.setFont("helvetica", "bold")
    doc.text("Recommendations", 14, currentY)
    currentY += 4
    autoTable(doc, {
      startY: currentY,
      head: [["#", "Recommendation"]],
      body: data.recommendations.map((entry, index) => [String(index + 1), entry]),
      theme: "grid",
      headStyles: { fillColor: [41, 128, 185] },
      columnStyles: { 0: { cellWidth: 10 } },
    })
  }

  // One page per phase — a phase with no steps still gets its page and signature line.
  data.method.forEach((phase, phaseIndex) => {
    doc.addPage()
    doc.setFontSize(16)
    doc.setFont("helvetica", "bold")
    doc.text(`${phaseIndex + 1}. ${phase}`, 14, 22)
    doc.setFontSize(10)
    doc.setFont("helvetica", "normal")
    doc.text(`${data.title} · v${data.version}`, 14, 29)

    let cursor = 40
    const steps = data.steps.filter((step) => step.phase === phase)

    if (steps.length === 0) {
      doc.setFontSize(11)
      doc.setTextColor(110)
      doc.text("No steps written for this phase yet.", 14, cursor)
      doc.setTextColor(0)
      cursor += 10
    }

    for (const step of steps) {
      if (cursor > 240) {
        doc.addPage()
        cursor = 20
      }
      doc.setFontSize(12)
      doc.setFont("helvetica", "bold")
      const heading = doc.splitTextToSize(`${step.order}. ${step.action}`, 180) as string[]
      doc.text(heading, 14, cursor)
      cursor += heading.length * 5 + 2

      const rows: [string, string][] = []
      if (step.checks.length > 0) rows.push(["Checks", step.checks.map((entry) => `• ${entry}`).join("\n")])
      if (step.expected) rows.push(["Expected", step.expected])
      if (step.precautions.length > 0) {
        rows.push(["Precautions", step.precautions.map((entry) => `• ${entry}`).join("\n")])
      }
      if (step.warnings.length > 0) {
        rows.push(["Warnings", step.warnings.map((entry) => `• ${entry}`).join("\n")])
      }
      if (step.ppe.length > 0) rows.push(["PPE", step.ppe.join(", ")])
      if (step.tools_parts.length > 0) rows.push(["Tools & parts", step.tools_parts.join(", ")])
      if (step.time_estimate) rows.push(["Time estimate", step.time_estimate])
      if (step.stop_condition) rows.push(["Stop if", step.stop_condition])
      if (step.escalation) rows.push(["Escalate to", step.escalation])
      if (step.evidence_to_record) rows.push(["Record", step.evidence_to_record])

      if (rows.length > 0) {
        autoTable(doc, {
          startY: cursor,
          head: [["Field", "Detail"]],
          body: rows,
          theme: "grid",
          styles: { fontSize: 9, cellPadding: 1.5 },
          headStyles: { fillColor: [41, 128, 185] },
          columnStyles: { 0: { cellWidth: 35, fontStyle: "bold" } },
        })
        cursor = (doc as any).lastAutoTable.finalY + 8
      } else {
        cursor += 6
      }
    }

    const pageHeight = doc.internal.pageSize.getHeight()
    let signatureY = Math.min(cursor + 14, pageHeight - 40)
    if (signatureY < cursor + 6) {
      doc.addPage()
      signatureY = 40
    }
    const width = doc.internal.pageSize.getWidth()
    doc.setFontSize(9)
    doc.setTextColor(80)
    doc.text("Performed by", 14, signatureY)
    doc.line(14, signatureY + 8, 70, signatureY + 8)
    doc.text("Signature", width / 2 - 20, signatureY)
    doc.line(width / 2 - 20, signatureY + 8, width / 2 + 30, signatureY + 8)
    doc.text("Date", width - 40, signatureY)
    doc.line(width - 40, signatureY + 8, width - 14, signatureY + 8)
    doc.setTextColor(0)
  })

  addFooter(doc)
  doc.save(filename("playbook", stamp))
}
