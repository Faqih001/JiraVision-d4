import { describe, expect, it } from "vitest"
import { readFileSync } from "node:fs"
import { resolve } from "node:path"

const source = readFileSync(resolve("lib/export/pdf.ts"), "utf8")

describe("the PDF export module", () => {
  it("exports the report, log and plan layouts", () => {
    expect(source).toContain("export function exportReportPdf")
    expect(source).toContain("export function exportLogPdf")
    expect(source).toContain("export function exportPlanPdf")
  })

  it("uses jspdf and jspdf-autotable", () => {
    expect(source).toMatch(/import.*jsPDF.*from ["']jspdf["']/u)
    expect(source).toMatch(/import.*autoTable.*from ["']jspdf-autotable["']/u)
  })

  it("follows the filename convention jiravision-<scope>-<stamp>.pdf", () => {
    expect(source).toContain("jiravision-${scope}-${stamp}.pdf")
  })

  it("adds a footer with page numbers and generation date", () => {
    expect(source).toContain("addFooter")
    expect(source).toContain("Page ${i} of ${pageCount}")
    expect(source).toContain("Generated by JiraVision")
  })

  it("report layout includes cover block with author, period, status", () => {
    expect(source).toContain("Author:")
    expect(source).toContain("Period:")
    expect(source).toContain("Status:")
  })

  it("report layout includes KPI strip", () => {
    expect(source).toContain("KPI")
    expect(source).toMatch(/Entries[\s\S]*?Hours[\s\S]*?Tasks done/)
  })

  it("log layout includes entries and deliverables tables", () => {
    expect(source).toMatch(/Work Log[\s\S]*?Entries[\s\S]*?Deliverables/)
  })

  it("plan layout includes lane-grouped table", () => {
    expect(source).toContain("lanes")
    expect(source).toContain("lane.name")
  })

  it("exports a fourth playbook layout with one page per phase", () => {
    expect(source).toContain("export function exportPlaybookPdf")
    expect(source).toContain("One page per phase")
    expect(source).toContain("Signature")
  })

  it("says on the sheet when the prose is still model-drafted", () => {
    expect(source).toContain("aiMarked: boolean")
    expect(source).toContain("Model draft")
    expect(source).toContain('"Precautions (model-drafted)"')
  })
})
